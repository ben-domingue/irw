"""Covariance family (irw_cov, source = "cov"): Warne & Burningham (2019) cognitive-test correlation matrices from 31 non-Western nations.

Source: OSF project tgq5y, "Spearman's g Found in 31 Non-Western Nations:
Strong Evidence that g is a Universal Phenomenon" (materials for Warne, R. T.,
& Burningham, C. (2019). Spearman's g found in 31 non-Western nations: Strong
evidence that g is a universal phenomenon. Psychological Bulletin, 145(3),
237-272, https://doi.org/10.1037/bul0000184).
Licence: CC BY 4.0 (stated on the node).

One deposit file is read AS TEXT, "Analysis 03212018.sps" (OSF file nz8mc), an
SPSS syntax file; it is never run. Per its header, each dataset is a block of
comment lines ("*...") describing the sample and citing the source table and
page, followed by
    MATRIX DATA VARIABLES=ROWTYPE_ <abbreviated variable names>.
    BEGIN DATA
    N <n> <n> ...
    CORR 1
    CORR r21 1
    ...
    END DATA.
and then factor-analysis syntax and comment lines reporting the authors'
factor-retention results (not used). There are 108 blocks. The other two .sps
files in the node repeat subsets of these matrices for other analyses.

Each block is one group, labelled "<first author> <year>" from the citation in
its description line, with a letter suffix when one source gives several
matrices (in file order). Values are the text as deposited (e.g. ".153"). The
description line is kept verbatim as the population. The N row is the same for
every variable in every block (three blocks list it once more than there are
variables; the value is the same); when the comments say pairwise deletion was used
the N is the maximum n and `missing` is "pairwise".

Not built (listed in records.json "held", with the reason):
- partial-correlation matrices (age, or age and SES, partialled out): not
  zero-order correlations;
- Condon & Revelle (2016) Indian and Filipino samples: computed by the
  meta-analysts from the openly available ICAR item responses (raw data exist);
- Bangirana (2015): computed by the meta-analysts from raw data shared by the
  authors (the paper's table of samples says "Data obtained via personal
  communication", where the other shared samples say "Correlation matrix
  obtained"; the meta-analysts selected 90 controls and used multiple
  imputation, paper p. 18);
- Ruffieux (2009): the deposit says the matrix was generated by multiple
  imputation (20 imputations), so it is not a reported matrix;
- Pitchford & Outhwaite (2016): the deposit replaces the article's printed
  -.90 by -.09 on the author's word, so the deposited matrix is not as printed;
- van de Vijver (2002), both samples: one cell is a correlation over both
  samples combined (n = 702), so neither matrix is a single sample's.
The meta-analysts left out non-cognitive, demographic and total-score variables
of some printed matrices (the comments say which); the matrices are therefore
subsets of the printed ones, with values unchanged.

Modification (2026-11-18): reshaped to the long lower-triangle layout in
data/covariance/README.md, one group per block; labels added as described.

Usage: python3 data/covariance/osf_warne2019_g.py <out dir>
"""
import csv
import json
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

URL = "https://osf.io/download/nz8mc/"
TABLE = "warne_2019_nonwesterng"
# the authors' factor-retention results ("Larsen & Warne (2010) result: ...", "Velicer (1976) MAP
# result: ...", with year typos in places) and the not-PD remark are not sample descriptions
NOISE = re.compile(r"^(Larsen & Warne|Velicer|MAP) \(\d{4}\)|^Matrix is not positive definite")
HOLD = {
    "Bhatia 1955b": "partial correlations (age partialled out); same data as Bhatia 1955a",
    "Sternberg 2001b": "partial correlations (age and SES partialled out); same sample as Sternberg 2001a",
    "Condon 2016a": "computed by the meta-analysts from open ICAR item responses (raw data exist)",
    "Condon 2016b": "computed by the meta-analysts from open ICAR item responses (raw data exist)",
    "Bangirana 2015": "computed by the meta-analysts from raw data (paper, table of samples: 'Data obtained via personal "
                      "communication (M. Boivin)'; 90 controls selected; multiple imputation)",
    "Ruffieux 2009": "deposit: 'Multiple imputation (20 imputations) used to generate correlation matrix'; not as reported",
    "Pitchford 2016": "deposit replaces the printed -.90 (manual processing speed with short-term memory) by -.09 "
                      "on the author's word; not as printed",
    "van de Vijver 2002a": "one cell (the two inductive reasoning measures) is pooled over both samples, n = 702",
    "van de Vijver 2002b": "one cell (the two inductive reasoning measures) is pooled over both samples, n = 702",
}


def get(url):
    """GET with retries: OSF answers 403/429 when downloads come too fast."""
    for wait in (0, 5, 15, 45, 90):
        time.sleep(wait)
        req = urllib.request.Request(url, headers={"User-Agent": "irw-cov-build"})
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code not in (403, 429, 502, 503):
                raise
    raise SystemExit(f"download failed after retries: {url}")


def blocks(text):
    """Yield (comment lines, variable names, data rows) for each MATRIX DATA block."""
    prev = 0
    # the variable list may wrap over several lines (three blocks do)
    for m in re.finditer(r"^MATRIX DATA VARIABLES=ROWTYPE_ (.*?)\.\s*\nBEGIN DATA", text, re.M | re.S):
        comments = [l[1:].strip() for l in text[prev:m.start()].split("\n")
                    if l.startswith("*") and not NOISE.match(l[1:].strip())]
        b = text.index("BEGIN DATA", m.start())
        e = text.index("END DATA", b)
        rows = [l.split() for l in text[b + len("BEGIN DATA"):e].strip().split("\n")]
        yield comments, m.group(1).split(), rows
        prev = e


def main(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    text = get(URL).decode("utf-8-sig").replace("\r\n", "\n")
    parsed = []
    n_blocks = len(re.findall(r"^MATRIX DATA", text, re.M))
    for comments, names, rows in blocks(text):
        if not parsed:                      # the file header precedes the first block
            comments = comments[-1:]
        desc = [c for c in comments if re.search(r"\((?:[^()]|\([^()]*\))*\b(1[89]\d\d|20\d\d)[a-z]?\b", c)]
        if not desc:
            raise SystemExit(f"no description line before {names[:3]}")
        d = desc[0]
        par = re.search(r"\(([^()]*)\)\.?\s*$", d)
        segs = [x.strip() for x in par.group(1).split(";")] if par else []
        segs = [x for x in segs if re.search(r"\b(1[89]\d\d|20\d\d)[a-z]?\b", x)]
        if not segs:
            raise SystemExit(f"no citation in {d!r}")
        year = re.search(r"\b((?:1[89]\d\d|20\d\d)[a-z]?)\b", segs[0]).group(1)
        first = re.split(r",| &| et al| and ", segs[0])[0].strip()
        parsed.append({"key": f"{first} {year}", "desc": d, "comments": comments,
                       "names": names, "rows": rows})
    if len(parsed) != n_blocks:
        raise SystemExit(f"parsed {len(parsed)} of {n_blocks} MATRIX DATA blocks")
    seen = {}
    for p in parsed:
        seen[p["key"]] = seen.get(p["key"], 0) + 1
    count = {}
    long, records, held = [], [], []
    for p in parsed:
        k = p["key"]
        if seen[k] > 1:
            count[k] = count.get(k, 0) + 1
            label = f"{k}{chr(96 + count[k])}"
        else:
            label = k
        names, rows = p["names"], p["rows"]
        K = len(names)
        if len(set(names)) != K or rows[0][0] != "N" or len(rows) != K + 1:
            raise SystemExit(f"{label}: unexpected block layout")
        ns = set(rows[0][1:])
        if len(rows[0]) < K + 1 or len(ns) != 1:      # three blocks repeat N once too often
            raise SystemExit(f"{label}: N row {rows[0]}")
        extra_n = len(rows[0]) - (K + 1)
        n = int(ns.pop())
        for a, r in enumerate(rows[1:]):
            if r[0] != "CORR" or len(r) != a + 2 or r[-1] != "1":
                raise SystemExit(f"{label}: row {a + 1} {r}")
            for v in r[1:-1]:
                if abs(float(v)) >= 1:
                    raise SystemExit(f"{label}: |r| >= 1 ({v})")
        if label in HOLD:
            held.append((label, HOLD[label]))
            continue
        for a in range(K):
            for b in range(a + 1):
                long.append({"stat": "cor", "var1": names[a], "var2": names[b],
                             "value": rows[a + 1][b + 1], "n": n, "group": label})
        text_all = " ".join(p["comments"]).lower()
        records.append({"group": label, "n_obs": n, "variables": names, "description": p["desc"],
                        "comments": [c for c in p["comments"] if c != p["desc"]],
                        "missing": "pairwise" if "pairwise" in text_all else "unknown", "extra_n_entries": extra_n})
    unused = set(HOLD) - {h[0] for h in held}
    if unused:
        raise SystemExit(f"hold labels not found: {unused}")
    with open(out / f"{TABLE}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["stat", "var1", "var2", "value", "n", "group"])
        w.writeheader()
        w.writerows(long)
    with open(out / f"{TABLE}_records.json", "w") as f:
        json.dump({"table": TABLE, "records": records, "held": held}, f, indent=1, ensure_ascii=False)
    print(f"wrote {TABLE}.csv: {len(records)} matrices built, {len(held)} held")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 osf_warne2019_g.py <out dir>")
    main(sys.argv[1])
