# Source: https://zenodo.org/records/16008605
# DOI: 10.5281/zenodo.16008605 (dataset; the record names no published paper)
#   Rumangkit, Stefanus (2025). Dataset Questionnaire Product Features on Resubscription
#   Intention and Electronic Word of Mouth Mediated by Customer Satisfaction on Film
#   Streaming Platforms [Dataset]. Zenodo.
# Data: "51_Retno et al_ICOBIRD_2025 (rev170725).xlsx", sheet "Form Responses 1": 222
#       respondents, 44 items on a 1-5 scale, in ten labelled blocks -- BB (6), RKL (3),
#       KAE (3), KST (3), KF (3), KBL (3), DTF (3), KP (8), NBU (6), EWM (6).
