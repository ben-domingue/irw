#!/usr/bin/env python3
"""Item text for the five fauziah_2026_* tables (Zenodo 21963745).

The Google Form export's column headers are the administered Indonesian stems
("Part A [Atasan saya mengakui ...]"). data/fauziah_2026_human_ai.py assigns the
SmartPLS codes (HL1.., PS1.., IM1.., HACC1.., IWB1..) by column order within each
Part; this script re-reads the same workbook and applies the same rule, so the
code->stem tie is the script's own map. The export stores the 1-5 answers as
numbers only and the record publishes no anchors, so option_text is blank (the
audit WARN is expected). English translations are IRW's (translation_source =
irw_generated) and are disclosed on the issues page.
"""
import csv
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent.parent
OUT_DIR = HERE / "itemtext_output"
RESP_DIR = HERE / "irw_output"
RAW = HERE / "runs" / "raw" / "10_5281_zenodo_21963745" / "Data responden kuesioner PS, IM, HL, HACC, IWB.xlsx"
COLS = ["table", "section_id", "item", "instrument", "language", "instructions", "section_prompt",
        "item_text", "correct_response", "option_text", "resp", "instructions_translated",
        "section_prompt_translated", "item_text_translated", "option_text_translated"]
PARTS = {"Part A": ("HL", "fauziah_2026_humble_leadership", "Humble leadership scale (Part A), 6 items"),
         "Part B": ("PS", "fauziah_2026_psych_safety", "Psychological safety scale (Part B), 7 items"),
         "Part C": ("IM", "fauziah_2026_intrinsic_motivation", "Intrinsic motivation scale (Part C), 3 items"),
         "Part D": ("HACC", "fauziah_2026_human_ai_collab", "Human-AI collaboration capability scale (Part D), 6 items"),
         "Part E": ("IWB", "fauziah_2026_iwb", "Innovative work behavior scale (Part E), 10 items")}
EN = {
    "HL1": "My supervisor acknowledges that they have limitations in work knowledge or ability.",
    "HL2": "My supervisor is willing to accept criticism and feedback to improve the way they work.",
    "HL3": "My supervisor values the abilities and strengths of every employee.",
    "HL4": "My supervisor shows appreciation for the contributions employees make.",
    "HL5": "My supervisor is open to ideas and suggestions from employees.",
    "HL6": "My supervisor is willing to learn from employees' experience and input.",
    "PS1": "I feel safe putting forward new ideas at work.",
    "PS2": "I feel I can discuss work difficulties openly with co-workers and my supervisor.",
    "PS3": "I feel safe trying new ways of working even though they might fail.",
    "PS4": "I feel comfortable asking co-workers for help when I face difficulties at work.",
    "PS5": "I feel my ideas are still valued even when they differ from other people's at work.",
    "PS6": "I feel that unintentional mistakes at work are seen as part of the learning process, not as grounds for blame.",
    "PS7": "I feel my abilities and contributions are valued in my work team.",
    "IM1": "I feel happy when my work gives me the chance to learn new things.",
    "IM2": "I feel satisfied when I face interesting challenges in my work.",
    "IM3": "I feel satisfied when I succeed in completing difficult work.",
    "HACC1": "I understand what AI can do to help me complete my work.",
    "HACC2": "I understand AI's limitations, so I know when AI output needs to be reviewed.",
    "HACC3": "I re-evaluate the output AI gives me before using it in my work.",
    "HACC4": "I can judge whether recommendations or information generated by AI are accurate and relevant.",
    "HACC5": "I am able to give the right instructions (prompts) so that AI produces information that fits my work needs.",
    "HACC6": "I can collaborate effectively with AI to complete work tasks.",
    "IWB1": "I pay attention to problems that lie outside my routine work.",
    "IWB2": "I often think about how to improve existing work processes.",
    "IWB3": "I look for new methods, techniques or ways of working to improve my work.",
    "IWB4": "I generate original solutions to solve work problems.",
    "IWB5": "I find new approaches to completing my tasks.",
    "IWB6": "I try to make others enthusiastic about the innovative ideas I propose.",
    "IWB7": "I try to convince others to support the innovative ideas I put forward.",
    "IWB8": "I apply innovative ideas systematically in work practice.",
    "IWB9": "I contribute to the implementation of new ideas in the workplace.",
    "IWB10": "I try to develop new things that can improve the work.",
}


def main() -> None:
    d = pd.read_excel(RAW)
    n = {k: 0 for k in PARTS}
    stems = {}
    for c in d.columns:
        for part, (pre, _, _) in PARTS.items():
            if str(c).startswith(part + " ["):
                n[part] += 1
                stems[f"{pre}{n[part]}"] = str(c)[len(part) + 2:].rstrip("]").strip()
    assert set(stems) == set(EN), set(stems) ^ set(EN)
    for part, (pre, table, instr) in PARTS.items():
        resp = pd.read_csv(RESP_DIR / f"{table}.csv")
        items = [i for i in stems if i.startswith(pre) and i[len(pre):].isdigit()]
        assert set(items) == set(resp["item"]), (table, set(items) ^ set(resp["item"]))
        assert set(resp["resp"]) <= {1, 2, 3, 4, 5}
        rows = []
        for it in items:
            for r in sorted(resp.loc[resp["item"] == it, "resp"].unique()):
                rows.append({"table": table, "section_id": f"{table}_1", "item": it, "instrument": instr,
                             "language": "Indonesian", "instructions": "", "section_prompt": "",
                             "item_text": stems[it], "correct_response": "", "option_text": "", "resp": int(r),
                             "instructions_translated": "", "section_prompt_translated": "",
                             "item_text_translated": EN[it], "option_text_translated": ""})
        with open(OUT_DIR / f"{table}__items.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=COLS, quoting=csv.QUOTE_ALL)
            w.writeheader()
            w.writerows(rows)
        print(table, len(rows), "rows")


if __name__ == "__main__":
    main()
